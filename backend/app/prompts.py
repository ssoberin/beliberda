def user_message(description, categories, title='', source_category=None):
    return {'role': 'user', 'content': json.dumps({
        'title': title, 'description': description, 'source_category': source_category,
        'requested_categories': [{'id': c, 'name': NAMES[c]} for c in categories],
    }, ensure_ascii=False)}


def assistant_message(drafts):
    return {'role': 'assistant', 'content': json.dumps({'drafts': drafts}, ensure_ascii=False)}


