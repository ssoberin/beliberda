# ------------------------------------------------------------------ помощники
def bullets(items):
    e = rnd.choice(EMO)
    style = rnd.choice(["list", "inline", "list"])
    if style == "inline":
        return rnd.choice(["Выполняем: ", "Что делаем: ", "Услуги: ", ""]) + ", ".join(items) + "."
    head = rnd.choice(["Что делаем:", "Наши услуги:", "Выполняем:", "С чем помогу:", ""])
    body = "\n".join(f"{e} {it[0].upper() + it[1:]}" for it in items)
    return (head + "\n" if head else "") + body


def cap(s):
    return s[0].upper() + s[1:]


def common_blocks(k_terms=(1, 3), filler=(0, 1)):
    name = rnd.choice(FIRST)
    ctx = dict(name=name, exp=rnd.randint(5, 20), n=rnd.randint(3, 8), city=rnd.choice(CITY))
    parts = []
    intro = rnd.choice(INTRO).format(**ctx)
    if intro: parts.append(intro)
    t = rnd.sample(TERMS, rnd.randint(*k_terms))
    parts.append(" ".join(t) if rnd.random() < .5 else "\n".join(f"{rnd.choice(EMO)} {x}" for x in t))
    for _ in range(rnd.randint(*filler)): parts.append(rnd.choice(FILL))
    g = rnd.choice(GEO).format(**ctx)
    if g: parts.append(g)
    c = rnd.choice(CTA)
    if c: parts.append(c)
    return parts


def labels(ids):
    return [{"mcId": i, "label": NAMES[i]} for i in sorted(set(ids))]


ads = []
def add(t, title, desc, ids, conf, note):
    ads.append({"item_id": f"syn-{t}-{len(ads)+1:04d}", "title": title, "description": desc.strip(),
                "found_microcategories": labels(ids), "mcId": 101, "type": t, "confidence": conf, "note": note})


