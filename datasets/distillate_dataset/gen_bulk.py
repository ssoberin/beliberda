def gen_C():
    k = rnd.choice([1, 1, 2, 2, 3])
    items = rnd.sample(C_ITEMS, k)
    ids = sorted({i for it in items for i in it[1]})
    conf = "medium" if any(it[2] == "medium" for it in items) else "high"
    note = "; ".join(filter(None, (it[3] for it in items))) or "граничный случай"
    sents = [it[0] for it in items]
    if rnd.random() < .5:
        body = cap("; ".join(sents)) + "."
    else:
        body = bullets(sents)
    title = rnd.choice(["Ремонт квартир", "Отделочные работы", "Мастер по ремонту", "Ремонт ванной и кухни",
                        "Частный мастер", "Ремонт квартир и домов", "Отделка квартир", "Бригада отделочников"])
    parts = common_blocks(filler=(0, 1))
    parts.insert(1 if len(parts) > 1 else 0, body)
    add("C", title, "\n\n".join(parts), ids, conf, note)


