def corrupt(text, level):
    for pat, rep in TYPO:
        if rnd.random() < level:
            text = re.sub(pat, rep, text, flags=re.I)
    # запятые/точки
    if rnd.random() < level: text = text.replace(",", "")
    if rnd.random() < level * .6: text = re.sub(r"\.\s", " ", text)
    # регистр
    r = rnd.random()
    if r < level * .4: text = text.lower()
    elif r < level * .55:
        words = text.split(); i = rnd.randrange(len(words)); j = min(len(words), i + rnd.randint(2, 6))
        words[i:j] = [w.upper() for w in words[i:j]]; text = " ".join(words)
    # лишние знаки
    if rnd.random() < level * .5: text = re.sub(r"!", "!!!", text)
    if rnd.random() < level * .3: text += rnd.choice([")))", ")", "!!!", "...", " ;)"])
    # случайные опечатки: пропуск/дубль буквы
    chars = list(text)
    # Never damage short operators (НЕ, НИ, НЕТ), change only long words.
    safe_positions = [i for m in re.finditer(r"[А-Яа-яЁё]{6,}", text) for i in range(m.start()+1, m.end()-1)]
    for _ in range(int(len(chars) * level * 0.004)):
        if not safe_positions: break
        i = rnd.choice(safe_positions)
        if chars[i].isalpha():
            if rnd.random() < .5: chars[i] = ""
            else: chars[i] = chars[i] * 2
    text = "".join(chars)
    return re.sub(r"  +", " ", text).strip()

def cap(s): return s[:1].upper() + s[1:] if s else s

def plural(s):
    # грубое превращение 1 л. ед. ч. в мн. ч. (не идеально — это и есть «неграмотность»)
    return re.sub(r"(ю|у)\b", lambda m: {"ю": "ем", "у": "ем"}[m.group(1)], s)

