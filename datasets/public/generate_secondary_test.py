def make_rows() -> list[dict]:
    rng = random.Random(20261114)
    rows = []
    for location_id, (object_name, where, deadline) in enumerate(PLACES):
        for variant in range(20):
            is_positive = variant >= 10
            serial = location_id * 20 + variant
            rng_row = random.Random(20261114 + serial * 7919)
            structural_options = (
                STRUCTURAL if location_id in (2, 3, 8, 12, 13, 14)
                else [STRUCTURAL[i] for i in (0, 1, 2, 3, 5, 6, 9)]
            )
            title = f"Ремонт {object_name}: " + rng_row.choice(
                ["частная бригада", "поэтапная смета", "выезд мастера", "работы по договору", "без посредников"]
            )
            lines = [rng_row.choice(OPENINGS)]
            lines.append(f"Занимаемся ремонтом {object_name}. В {where} сначала проверяем, что уже сделано, "
                         f"и обсуждаем график {deadline}. Не назначаем одинаковую смету всем клиентам.")
            if is_positive:
                # Reproduce the sparse and multi-label examples without borrowing test text or labels.
                size = [1, 2, 2, 3, 3, 4, 4, 5, 1, 2][variant - 10]
                selected = sorted(rng_row.sample(range(5), size))
                lines.append("Что берём на себя по согласованной смете:")
                for idx in selected:
                    lines.append("• " + rng_row.choice(OFFER[idx]))
                if size < 5:
                    excluded = rng_row.choice([i for i in range(5) if i not in selected])
                    lines.append("Обратите внимание: " + EXCLUDED[excluded])
                lines.append("Помимо перечисленного берём на себя "
                             + rng_row.choice(structural_options) + ".")
            else:
                first, second = rng_row.sample(structural_options, 2)
                lines.append("Из практических задач берём " + first + ", а также " + second + ".")
                if variant % 3 == 0:
                    lines.append("В сообщениях часто спрашивают: «А вы делаете штукатурку, плитку, "
                                 "сантехнику, электрику и покраску?» Нет: это не перечень наших услуг. "
                                 "Для этих этапов приглашайте профильных мастеров.")
                elif variant % 3 == 1:
                    lines.append("Объект может быть заявлен как «ремонт под ключ», но у нас договор "
                                 "только на названные выше конструкции и организацию работ. "
                                 "Монтаж инженерии и финишную отделку заказчик поручает другим.")
                else:
                    lines.append("По плану заказчика здесь будут плитка, новые розетки, "
                                 "раковина и обои; это пожелания к готовому помещению, "
                                 "не работы нашей бригады. Готовим только согласованный этап.")
            lines.append("Порядок простой: осмотр, список задач, стоимость и последовательность. "
                         "Если при вскрытии обнаружится скрытая проблема, сначала сообщим о ней "
                         "и согласуем изменение объёма, а не будем молча добавлять позиции.")
            lines.append(rng_row.choice(ENDINGS))
            rows.append({"title": title, "description": "\n\n".join(lines),
                         "categories": [LABELS[i] for i in selected] if is_positive else []})
    rng.shuffle(rows)
    return rows


if __name__ == "__main__":
    schema = pa.schema([
        pa.field("title", pa.string()),
        pa.field("description", pa.string()),
        pa.field("categories", pa.list_(pa.string())),
    ])
    rows = make_rows()
    assert len(rows) == 300
    assert len({row["description"] for row in rows}) == 300
    table = pa.Table.from_pylist(rows, schema=schema)
    pq.write_table(table, OUTPUT, compression="zstd")
    print(f"Wrote {len(rows)} rows to {OUTPUT}")
